#!/usr/bin/env node
/**
 * update-fireworks-models.mjs
 *
 * Regenerates the Fireworks endpoint block in librechat-config.yaml with the
 * current top-trending serverless LLMs from the Fireworks Model Library.
 *
 * Data source: https://app.fireworks.ai/api/models — the same unauthenticated
 * JSON feed that backs https://app.fireworks.ai/models. The UI's "Trending"
 * sort is computed client-side as:
 *
 *     featuredPriority desc  →  has "New" tag desc  →  createTime desc
 *
 * (see sortModelsByDisplayPriority in the app bundle), which this script
 * replicates. Models are filtered to what LibreChat can actually serve:
 * public text models, serverless-available, state "Ready".
 *
 * Usage:
 *   node scripts/update-fireworks-models.mjs           # rewrite in place
 *   node scripts/update-fireworks-models.mjs --check   # exit 1 if stale (CI)
 *
 * Runs weekly via .github/workflows/update-fireworks-models.yml.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_PATH = join(REPO_ROOT, 'librechat-config.yaml');
const MODELS_API = 'https://app.fireworks.ai/api/models';
const MAX_MODELS = 25;
const MIN_SANE_MODEL_COUNT = 5; // abort if the feed shape appears to have changed
const START_MARKER = '# FIREWORKS-ENDPOINT:START';
const END_MARKER = '# FIREWORKS-ENDPOINT:END';

/**
 * Preferred title/summarization models, by ID prefix, chosen for low cost and
 * speed. The first one present in the trending list wins; otherwise the top
 * trending model is used.
 */
const TITLE_MODEL_PREFIXES = ['deepseek-v4-flash', 'gpt-oss-20b', 'nemotron-lightning'];

async function fetchTrendingServerlessModels() {
  const res = await fetch(MODELS_API, { headers: { Accept: 'application/json' } });
  if (!res.ok) {
    throw new Error(`Fireworks model feed returned ${res.status} ${res.statusText}`);
  }
  const models = await res.json();
  if (!Array.isArray(models)) {
    throw new Error('Fireworks model feed did not return an array; shape may have changed');
  }

  const eligible = models.filter(
    (m) =>
      m.type === 'text' &&
      m.serverless === true &&
      m.stateText === 'Ready' &&
      m.public === true,
  );

  // The app.fireworks.ai "Trending" sort (sortModelsByDisplayPriority).
  eligible.sort((a, b) => {
    const byFeatured = (b.featuredPriority ?? 0) - (a.featuredPriority ?? 0);
    if (byFeatured !== 0) {
      return byFeatured;
    }
    const byNew = (b.tags?.includes('New') ? 1 : 0) - (a.tags?.includes('New') ? 1 : 0);
    if (byNew !== 0) {
      return byNew;
    }
    return (b.createTime ?? '').localeCompare(a.createTime ?? '');
  });

  return eligible.slice(0, MAX_MODELS).map((m) => m.name);
}

function pickTitleModel(modelNames) {
  for (const prefix of TITLE_MODEL_PREFIXES) {
    const match = modelNames.find((name) => name.endsWith(`/models/${prefix}`) || name.split('/').pop().startsWith(prefix));
    if (match) {
      return match;
    }
  }
  return modelNames[0];
}

function renderEndpointBlock(modelNames) {
  const today = new Date().toISOString().slice(0, 10);
  const titleModel = pickTitleModel(modelNames);
  const items = modelNames.map((name) => `          "${name}",`).join('\n');
  // Strip the trailing comma on the final entry for cleanliness.
  const list = items.replace(/,$/, '');

  return `${START_MARKER} — auto-generated by scripts/update-fireworks-models.mjs
    # (weekly via .github/workflows/update-fireworks-models.yml). Edit the script,
    # not this block; manual edits will be overwritten.
    - name: 'Fireworks'
      apiKey: '\${FIREWORKS_API_KEY}'
      baseURL: 'https://api.fireworks.ai/inference/v1'
      models:
        # Top trending serverless LLMs from https://app.fireworks.ai/models (Sort: Trending).
        # Snapshot: ${today}
        default: [
${list}
        ]
        fetch: false
      titleConvo: true
      titleModel: "${titleModel}"
      summarize: false
      modelDisplayLabel: 'Fireworks'
    ${END_MARKER}`;
}

function main() {
  const checkOnly = process.argv.includes('--check');
  return fetchTrendingServerlessModels().then((modelNames) => {
    if (modelNames.length < MIN_SANE_MODEL_COUNT) {
      throw new Error(
        `Only ${modelNames.length} eligible models found; refusing to update (feed shape may have changed)`,
      );
    }

    const config = readFileSync(CONFIG_PATH, 'utf8');
    const startIdx = config.indexOf(START_MARKER);
    const endIdx = config.indexOf(END_MARKER);
    if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
      throw new Error(
        `Markers not found in ${CONFIG_PATH}. Expected '${START_MARKER}' ... '${END_MARKER}'.`,
      );
    }

    const block = renderEndpointBlock(modelNames);
    const next =
      config.slice(0, startIdx) + block + config.slice(endIdx + END_MARKER.length);

    if (next === config) {
      console.log(`Fireworks models already up to date (${modelNames.length} models).`);
      return;
    }

    if (checkOnly) {
      console.error('Fireworks model list is stale. Run: node scripts/update-fireworks-models.mjs');
      process.exit(1);
    }

    writeFileSync(CONFIG_PATH, next);
    console.log(`Updated ${CONFIG_PATH} with ${modelNames.length} trending Fireworks models:`);
    for (const name of modelNames) {
      console.log(`  - ${name}`);
    }
    console.log(`Title model: ${pickTitleModel(modelNames)}`);
  });
}

main().catch((error) => {
  console.error(`update-fireworks-models: ${error.message}`);
  process.exit(1);
});
